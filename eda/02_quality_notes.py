"""Generate experiments/eda/data_quality_notes.md from the actual inventory/build outputs, so every
number in the notes can be traced to a script. Run after 01_inventory.py and build_dataset.py."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


import numpy as np
import pandas as pd

EDA, FEAT = "experiments/eda", "data/processed"
inv = pd.read_csv(f"{EDA}/dataset_inventory.csv", dtype={"trip_id": str})
bs = pd.concat([pd.read_csv(f"{FEAT}/build_summary_{p}.csv", dtype={"trip_id": str}) for p in ("train", "student_test")])
L = []
w = L.append
n = lambda p: int((inv.partition == p).sum())
w("# PathSnap data-quality notes (generated by eda/02_quality_notes.py)\n")
w(f"Partitions analysed: train = {n('train')} trips, student_test = {n('student_test')} trips. "
  "Evaluator-testing data was never used.\n")
w("## Checks that passed\n")
w(f"- All four files present for every trip: {bool(inv[['has_track','has_nodes','has_arcs','has_route']].all().all())}")
w(f"- Missing values in .track: {int(inv.n_missing_values.sum())}; invalid coordinates: {int(inv.n_invalid_coords.sum())}")
w(f"- Timestamps strictly increasing in every trip: {bool(inv.timestamps_monotonic.all())}; duplicate timestamps: {int(inv.n_duplicate_timestamps.sum())}")
w(f"- All route arc ids valid (< number of arcs): {bool(inv.route_arc_ids_valid.all())}")
w(f"- Isolated nodes (in no arc): {int(inv.n_isolated_nodes.sum())}\n")
w("## Issues found\n")
g = inv[inv.dt_max_s > 300]
w(f"1. **Irregular sampling / GPS gaps.** Mean share of 1 s steps: train {inv[inv.partition=='train'].frac_dt_1s.mean():.3f}, "
  f"student_test {inv[inv.partition=='student_test'].frac_dt_1s.mean():.3f}. "
  f"{len(g)} trips have a gap > 300 s (largest {inv.dt_max_s.max():.0f} s, trip {inv.loc[inv.dt_max_s.idxmax(),'trip_id']}). "
  f"Trips with the lowest 1 s share: " + ", ".join(f"{r.trip_id} ({r.frac_dt_1s:.2f})" for r in inv.nsmallest(3, 'frac_dt_1s').itertuples()) + ".")
w(f"2. **Road networks are not fully connected.** {int((inv.n_weak_components>1).sum())} of {len(inv)} networks have more than one weakly connected component "
  f"(median {inv.n_weak_components.median():.0f}); the largest holds {inv.largest_weak_comp_share.min()*100:.0f}-{inv.largest_weak_comp_share.max()*100:.0f}% of nodes. "
  f"Reference routes always stay inside one component (max components touched by a route: {int(inv.route_n_weak_components.max())}). "
  "Consequence for the HMM: transitions between components are impossible and must be handled explicitly.")
w(f"3. **Directed arcs / duplicates.** Road segments are directed (two-way streets appear as two arcs). {int(inv.n_duplicate_arcs.sum())} duplicate (u,v) arcs and "
  f"{int(inv.n_self_loops.sum())} self-loops exist. Arc ids are kept unchanged (the evaluator compares arc ids); duplicates are flagged by the feature is_dup_arc, self-loops get zero length.")
w(f"4. **Reference route is not perfectly continuous.** Share of consecutive route arcs that connect: min {inv.route_continuity.min():.3f}, mean {inv.route_continuity.mean():.4f}. "
  "Reference routes are treated as reference information, not verified ground truth.")
w(f"5. **No per-point label.** A trip has {inv.gps_per_route_arc.median():.1f} GPS points per route arc (median), so labels are derived by monotone alignment (src/labels.py).")
bad = bs[bs.label_valid_frac < 0.9]
w(f"6. **Incomplete reference routes.** After alignment, points farther than the candidate radius from their aligned arc are flagged label_valid = 0. "
  f"Train: {bs[bs.partition=='train'].label_valid_frac.mean()*100:.1f}% of trips' points valid on average; student_test: {bs[bs.partition=='student_test'].label_valid_frac.mean()*100:.1f}%. "
  + (f"Trips with < 90% valid labels: " + ", ".join(f"{r.trip_id} ({r.label_valid_frac*100:.0f}% of {r.n_points} pts)" for r in bad.itertuples()) + ". " if len(bad) else "")
  + "Training/evaluation should use label_valid = 1 rows only.\n")
w("## Assumptions and decisions\n")
w("- Distances use a per-trip local equirectangular projection (src/geo.py); each trip has its own network and trips span the globe, so no single global projection fits.")
w("- Candidate set: arcs within 50 m of the GPS point, at most 15 nearest; points with no arc within 50 m fall back to 150 m (flag is_fallback). Chosen from the train-only trade-off in candidate_radius_tradeoff.csv.")
w("- No GPS rows are dropped (the API must answer every observation); obs_idx keeps the raw row number.")
w("- Learned preprocessing (scaling etc.) is NOT fitted here; Member 2 must fit it inside each training fold only.")
open(f"{EDA}/data_quality_notes.md", "w").write("\n".join(L) + "\n")
print("\n".join(L))
